import random

def fun_game(die_sides):
  """this is a game to roll a use sided die 5 times"""
  die_rolls = [random.randint (1, die_sides) for die in range(5)]
  return die_rolls

def number_game():
  secret = random.randint(1, 10)
  guess = int(input("guess a number between 1 and 10: "))
  if guess == secret:
    return "You won!"
  else:
    return "You suck!"